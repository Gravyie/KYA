import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn, spawnSync} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {verify} from 'node:crypto';
import {createAuctent, AuctentDeniedError} from '../../../packages/agent-sdk/src/index.js';

test('registration, policy, receipt, integrity, rotation and revocation',async()=>{
  const dir=await mkdtemp(join(tmpdir(),'auctent-test-'));
  const port=53000+Math.floor(Math.random()*1000);
  const server=spawn(process.execPath,[resolve('apps/api/src/guard-server.js')],{env:{...process.env,AUCTENT_DATA_DIR:dir,PORT:String(port)},stdio:'ignore'});
  const base='http://127.0.0.1:'+port;
  async function request(path,method='GET',key='',body){const r=await fetch(base+path,{method,headers:{...(key?{authorization:'Bearer '+key}:{}),...(body?{'content-type':'application/json'}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()}}
  try{
    for(let i=0;i<40;i++){try{await request('/health');break}catch{await new Promise(r=>setTimeout(r,50))}}
    const home=await fetch(base+'/');assert.equal(home.status,200);assert.match(await home.text(),/Auctent/);
    assert.match(home.headers.get('content-security-policy'),/default-src 'self'/);
    const artwork=await fetch(base+'/images/bg-texture.webp');assert.equal(artwork.status,200);assert.equal(artwork.headers.get('content-type'),'image/webp');
    const setup=await request('/api/setup','POST','',{name:'Test owner'});assert.equal(setup.status,200);
    const owner=setup.data.key;
    assert.equal((await request('/api/dashboard')).status,401);
    const created=await request('/api/agents','POST',owner,{name:'Reader',scopes:[{action:'files.read',resources:['workspace/*'],maxAmount:0}]});assert.equal(created.status,200);
    const {agent,key}=created.data;
    const preview=await request('/api/preview','POST','',{scopes:[{action:'files.read',resources:['workspace/*'],maxAmount:0}],request:{action:'files.write',resource:'workspace/report.md'}});
    assert.equal(preview.data.decision.allowed,false);
    const simulated=await request('/api/agents/'+agent.id+'/simulate','POST',owner,{action:'files.read',resource:'workspace/report.md'});
    assert.equal(simulated.data.decision.allowed,true);
    assert.equal((await request('/api/agents/'+agent.id+'/simulate','POST')).status,401);
    const sdk=createAuctent({agentKey:key,baseUrl:base});
    let toolCalls=0;
    assert.equal(await sdk.run({action:'files.read',resource:'workspace/report.md'},()=>{toolCalls++;return 'real result'}),'real result');
    await assert.rejects(()=>sdk.run({action:'files.write',resource:'workspace/report.md'},()=>{toolCalls++}),AuctentDeniedError);
    assert.equal(toolCalls,1);
    const offline=createAuctent({agentKey:key,fetchImpl:async()=>{throw Error('offline')}});
    await assert.rejects(()=>offline.run({action:'files.read',resource:'workspace/report.md'},()=>{toolCalls++}),{code:'UNREACHABLE'});
    assert.equal(toolCalls,1);
    const exampleEnv={...process.env,AUCTENT_AGENT_KEY:key,AUCTENT_URL:base};
    assert.equal(spawnSync(process.execPath,[resolve('examples/guarded-agent.mjs'),'README.md'],{cwd:resolve('.'),env:exampleEnv,encoding:'utf8'}).status,0);
    const eventsBeforeEscape=(await request('/api/dashboard','GET',owner)).data.events.length;
    assert.notEqual(spawnSync(process.execPath,[resolve('examples/guarded-agent.mjs'),'/etc/hosts'],{cwd:resolve('.'),env:exampleEnv,encoding:'utf8'}).status,0);
    assert.equal((await request('/api/dashboard','GET',owner)).data.events.length,eventsBeforeEscape);
    const card=(await request('/api/agents/'+agent.id+'/card')).data;
    assert.ok(verify(null,Buffer.from(JSON.stringify(card.card)),card.publicKey,Buffer.from(card.signature,'base64url')));
    const registry=(await request('/api/registry')).data;
    assert.equal(registry.publicKey,card.publicKey);
    const verifyArgs=[resolve('examples/verify-card.mjs'),base+'/api/agents/'+agent.id+'/card',registry.fingerprint];
    assert.equal(spawnSync(process.execPath,verifyArgs,{encoding:'utf8'}).status,0);
    assert.notEqual(spawnSync(process.execPath,[...verifyArgs.slice(0,2),'0'.repeat(64)],{encoding:'utf8'}).status,0);
    const allowed=await request('/api/authorize','POST',key,{action:'files.read',resource:'workspace/report.md',amount:0});assert.equal(allowed.data.decision.allowed,true);
    const denied=await request('/api/authorize','POST',key,{action:'files.write',resource:'workspace/report.md'});assert.equal(denied.data.decision.allowed,false);
    const receipt=await request('/api/receipt','POST',key,{eventId:allowed.data.eventId,outcome:'success'});assert.equal(receipt.status,200);
    assert.equal((await request('/api/receipt','POST',key,{eventId:allowed.data.eventId,outcome:'success'})).status,409);
    assert.equal((await request('/api/audit/verify','GET',owner)).data.valid,true);
    const exportResponse=await request('/api/audit/export','GET',owner);
    assert.equal(exportResponse.data.count,exportResponse.data.events.length);
    assert.equal(exportResponse.data.head,exportResponse.data.events.at(-1).hash);
    assert.equal((await request('/api/audit/export')).status,401);
    const rotated=await request('/api/agents/'+agent.id+'/rotate','POST',owner);assert.equal(rotated.status,200);
    assert.equal((await request('/api/authorize','POST',key,{action:'files.read',resource:'workspace/report.md'})).status,401);
    await request('/api/agents/'+agent.id+'/revoke','POST',owner);
    assert.notEqual(spawnSync(process.execPath,verifyArgs,{encoding:'utf8'}).status,0);
    assert.equal((await request('/api/authorize','POST',rotated.data.key,{action:'files.read',resource:'workspace/report.md'})).data.decision.allowed,false);
    assert.equal((await request('/api/agents/'+agent.id+'/status')).data.active,false);
    assert.equal((await request('/api/audit/verify','GET',owner)).data.valid,true);
    assert.equal((await request('/api/owner/recover','POST','wrong-key')).status,401);
    const recovery=spawnSync(process.execPath,[resolve('scripts/recover-owner.mjs')],{cwd:resolve('.'),env:{...process.env,AUCTENT_DATA_DIR:dir,AUCTENT_URL:base},encoding:'utf8'});
    assert.equal(recovery.status,0,recovery.stderr);
    const recoveredKey=recovery.stdout.match(/auo_[A-Za-z0-9_-]+/)?.[0];
    assert.ok(recoveredKey);
    assert.equal((await request('/api/dashboard','GET',owner)).status,401);
    const recoveredDashboard=await request('/api/dashboard','GET',recoveredKey);
    assert.equal(recoveredDashboard.status,200);
    assert.equal(recoveredDashboard.data.agents[0].id,agent.id);
    assert.equal((await request('/api/registry')).data.fingerprint,registry.fingerprint);
    assert.equal((await request('/api/audit/verify','GET',recoveredKey)).data.valid,true);
    assert.equal(recoveredDashboard.data.events[0].kind,'owner.key.recovered');
  }finally{server.kill();await rm(dir,{recursive:true,force:true})}
});
